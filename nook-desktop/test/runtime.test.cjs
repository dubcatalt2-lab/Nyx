test('agent executes a multi-step fixture with real writes and verification; malformed/denied tools do not run', async () => {
  const f = fixture(), store = new Store(path.join(f.root, 'tasks.sqlite')), events = [];
  const broker = new Broker({...f, helper: '', approve: async () => true}); broker.grant(f.project, 2);
  const replies = [{message: 'Inspect', tool: 'list', args: {}}, {message: 'Write', tool: 'write', args: {path: 'result.txt', content: 'verified fixture', expectedHash: null}}, {message: 'Verify', tool: 'read', args: {path: 'result.txt'}}, {message: 'File written and verified', done: true}];
  const engine = new Engine({provider: {complete: async () => ({text: JSON.stringify(replies.shift())})}, broker, store, emit: value => events.push(value)});
  assert.equal((await engine.start({prompt: 'Create result', model: 'fixture'})).state, 'completed');
  assert.equal(fs.readFileSync(path.join(f.project, 'result.txt'), 'utf8'), 'verified fixture');
  assert(events.some(e => e.type === 'result' && e.body.result.verified));
  assert.throws(() => parse('{"message":"bad","tool":"eval","args":{}}'), /Unsupported/);
  broker.revoke(); replies.push({message: 'Read', tool: 'list', args: {}});
  assert.equal((await engine.start({prompt: 'Denied', model: 'fixture'})).state, 'failed');
  const pending = store.create('Interrupted'); store.close(); const reopened = new Store(path.join(f.root, 'tasks.sqlite'));
  assert.equal(reopened.tasks().find(t => t.id === pending).state, 'interrupted'); reopened.close();
});
