const fixture = () => { const root = fs.mkdtempSync(path.join(os.tmpdir(), 'nook-test-')); fs.mkdirSync(path.join(root, 'project')); return {root, project: path.join(root, 'project'), backup: path.join(root, 'backup')}; };
test('file tools verify writes, reject escapes, retain backups and refuse conflicting undo', () => {
  const f = fixture(), w = new Workspace(f.project, f.backup);
  const saved = w.write('sample.txt', 'first', null); assert(saved.verified);
  const before = w.read('sample.txt'); assert.equal(before.content, 'first');
  assert.throws(() => w.write('sample.txt', 'bad', null), /changed/);
  const edited = w.write('sample.txt', 'second', before.hash);
  assert.equal(w.read('sample.txt').content, 'second');
  w.undo(edited.id); assert.equal(w.read('sample.txt').content, 'first');
  assert.throws(() => w.undo(edited.id), /newer work/);
  for (const target of ['../private', 'C:/private', 'sample.txt:secret', '.env', '.ssh/key', 'CON', 'sample.txt.', 'nested/../secret']) assert.throws(() => w.resolve(target, true));
  fs.writeFileSync(path.join(f.root, 'secret.txt'), 'outside');
  fs.linkSync(path.join(f.root, 'secret.txt'), path.join(f.project, 'hard.txt'));
  assert.throws(() => w.read('hard.txt'), /linked/);
  fs.symlinkSync(f.root, path.join(f.project, 'junction'), 'junction');
  assert.throws(() => w.read('junction/secret.txt'), /junction/);
  assert.deepEqual(w.search('first').matches.map(item => item.path), ['sample.txt']);
});
test('permission levels, expiry, revocation during approval and elevation denial fail closed', async () => {
  const f = fixture(); let allow = true, onApprove = () => {};
  const b = new Broker({...f, helper: '', approve: async () => { onApprove(); return allow; }});
  await assert.rejects(b.run('list', {}), /outside/);
  b.grant(f.project, 1); assert.equal((await b.run('list', {})).entries.length, 0);
  await assert.rejects(b.run('write', {path: 'x', content: 'x', expectedHash: null}), /outside/);
  b.grant(f.project, 2); allow = false;
  await assert.rejects(b.run('write', {path: 'x', content: 'x', expectedHash: null}), /declined/);
  assert(!fs.existsSync(path.join(f.project, 'x')));
  allow = true; onApprove = () => b.revoke(); b.grant(f.project, 3);
  await assert.rejects(b.run('command', {command: 'Write-Output should-not-run'}), /permissions changed/);
  onApprove = () => {}; b.grant(f.project, 4); b.expires = 0;
  await assert.rejects(b.run('read', {path: 'x'}), /outside/);
  b.grant(f.project, 4); await assert.rejects(b.run('elevate', {command: 'Write-Output nope'}), /outside/);
  b.grant(f.project, 5); allow = false; await assert.rejects(b.run('elevate', {command: 'Write-Output nope'}), /declined/);
});
