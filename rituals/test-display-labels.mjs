import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {chromium} from 'playwright';
const browser=await chromium.launch({channel:'msedge',headless:true});
try {
 const page=await browser.newPage();
 await page.setContent(`<body><button data-nyx-dock-item="games" aria-label="Games"><span>Games</span></button><h1>Music</h1><h2 id="icon-title"><svg><path /></svg>Nyx API Keys</h2><div class="message"><h2>Games</h2></div><pre><h2>Music</h2></pre><textarea>Music</textarea><div contenteditable="true"><h2>Games</h2></div><span class="nyx-styled-display-name">Alice</span></body>`);
 await page.addScriptTag({content:await readFile('parables/display-names.js','utf8')});
 await page.waitForFunction(()=>document.querySelector('button span').textContent!=='Games');
 assert.equal((await page.locator('button span').textContent()).normalize('NFKC'),'G@M3Z');
 assert.equal((await page.locator('h1').textContent()).normalize('NFKC'),'MU$1C');
 assert.equal(await page.locator('textarea').inputValue(),'Music');
 assert.equal(await page.locator('[contenteditable] h2').textContent(),'Games');
 assert.equal(await page.locator('.nyx-styled-display-name').textContent(),'Alice');
 assert.equal(await page.getByRole('button',{name:'Games',exact:true}).count(),1);
 await page.evaluate(()=>document.querySelector('button span').textContent='Account');
 await page.waitForFunction(()=>document.querySelector('button span').textContent.normalize('NFKC')==='@CC0UN7');
 assert(await page.evaluate(()=>nyxDisplayName(nyxDisplayName('Games'))===nyxDisplayName('Games')));
 assert.equal((await page.locator('#icon-title').textContent()).normalize('NFKC'),'NYX @P1 K3Y$');
 assert.equal(await page.locator('#icon-title svg path').count(),1);
 assert.equal(await page.locator('.message h2').textContent(),'Games');
 assert.equal(await page.locator('pre h2').textContent(),'Music');
 assert.equal(await page.evaluate(()=>nyxDisplayName('AI')),'A1');
 assert.equal(await page.evaluate(()=>nyxDisplayName('A1')),'A1');
 assert.equal(await page.evaluate(()=>nyxDisplayName('Nyx AI').normalize('NFKC')),'NYX A1');
 await page.evaluate(()=>{
  document.body.insertAdjacentHTML('beforeend','<section id="wording"><input placeholder="Search games" value="search games"><p>Browse movies in your browser. Proxy scramjet games.</p><button title="Reload game">Random game</button><span>1,347 games</span><div class="ai-message-content">Search games with a proxy</div></section>');
 });
 await page.waitForFunction(()=>document.querySelector('#wording input').placeholder!=='Search games');
 assert.equal(await page.locator('#wording input').inputValue(),'search games');
 assert.equal(await page.locator('#wording input').getAttribute('aria-label'),'Search games');
 assert.equal(await page.locator('#wording .ai-message-content').textContent(),'Search games with a proxy');
 assert(!/\b(?:search|games?|browse|browser|proxy|scramjet|movies)\b/i.test(await page.locator('#wording p').textContent()));
 await page.locator('#wording button').evaluate(el=>{el.title='Play game';el.textContent='Play game';});
 await page.waitForFunction(()=>!document.querySelector('#wording button').title.includes('game'));
 assert(!/\b(?:play|game)\b/i.test(await page.locator('#wording button').textContent()));
 await page.evaluate(()=>document.body.insertAdjacentHTML('beforeend','<section id="connections"><p>Connection sites web reload website pages. https://sites.example.com/web/pages</p><button>Reload website</button><input value="wss://sites.example.com/web/" placeholder="Find websites"></section>'));
 await page.waitForFunction(()=>!document.querySelector('#connections button').textContent.includes('Reload'));
 assert(!/\b(?:connections?|sites?|web|reload|websites?|pages?)\b/i.test((await page.locator('#connections p').textContent()).split('https://')[0]));
 assert((await page.locator('#connections p').textContent()).includes('https://sites.example.com/web/pages'));
 assert.equal(await page.locator('#connections input').inputValue(),'wss://sites.example.com/web/');
 assert.equal(await page.getByRole('button',{name:'Reload website',exact:true}).count(),1);
 console.log('PASS dynamic/icon labels, idempotence, accessible names, editable text, messages, code and profile preservation.');
} finally {await browser.close()}
