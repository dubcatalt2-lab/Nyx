import assert from 'node:assert/strict';
import express from 'express';
import {resolve} from 'node:path';
import {chromium} from 'playwright';

const app=express();
app.get('/controls.js',(_req,res)=>res.sendFile(resolve('parables/document-controls.js'),{dotfiles:'allow'}));
app.get('/controls.css',(_req,res)=>res.sendFile(resolve('vestments/document-controls.css'),{dotfiles:'allow'}));
app.get('/assets/backgrounds/study-away-cover.png',(_req,res)=>res.sendFile(resolve('relics/backgrounds/study-away-cover.png'),{dotfiles:'allow'}));
app.get('/apps/music/',(_req,res)=>res.send('<!doctype html><button>Music app</button>'));
app.get('/',(_req,res)=>res.send(`<!doctype html><link rel="stylesheet" href="/controls.css"><button data-workspace-shell-back disabled>Back</button><button data-workspace-shell-forward disabled>Forward</button><button data-workspace-shell-reload>Reload</button><button data-workspace-shell-new-tab>New tab</button><button data-nyx-dock-item="settings" onclick="document.body.dataset.settings='opened'">Settings</button><input value="selection"><iframe srcdoc="<button>Inside app</button>"></iframe><script src="/controls.js" defer></script>`));
const server=app.listen(0,'127.0.0.1');await new Promise(resolve=>server.once('listening',resolve));
const workspace=await chromium.launch({channel:'msedge',headless:true});
try{
  const page=await workspace.newPage({viewport:{width:390,height:800}}),base=`http://127.0.0.1:${server.address().port}`;
  await page.goto(base);await page.mouse.click(380,780,{button:'right'});
  assert.equal(await page.locator('#nyxAwayCover').isVisible(),false);
  const menu=page.getByRole('menu',{name:'Nyx'});assert.equal(await menu.count(),1);
  assert.equal(await menu.getByRole('menuitem',{name:'Back',exact:true}).isDisabled(),true);
  const bounds=await menu.boundingBox();assert(bounds.x+bounds.width<=390);assert(bounds.y+bounds.height<=800);
  await menu.getByRole('menuitem',{name:'Settings',exact:true}).click();assert.equal(await page.locator('body').getAttribute('data-settings'),'opened');
  await page.locator('input').click({button:'right'});await page.getByRole('menuitem',{name:'Select all',exact:true}).click();
  assert.equal(await page.locator('input').evaluate(input=>input.selectionEnd-input.selectionStart),9);
  await page.mouse.click(100,700,{button:'right'});await page.keyboard.press('Escape');assert.equal(await page.getByRole('menu').count(),0);
  const switchVisibility=hidden=>{Object.defineProperty(document,'hidden',{configurable:true,value:hidden});document.dispatchEvent(new Event('visibilitychange'));};
  await page.locator('input').fill('preserved');
  await page.evaluate(switchVisibility,true);
  await page.locator('#nyxAwayCover').waitFor({state:'visible'});
  assert.equal(await page.locator('#nyxAwayCover img').evaluate(img=>img.complete&&img.naturalWidth>0),true);
  assert.equal(await page.locator('#nyxAwayCover').evaluate(el=>el.matches(':popover-open')),true);
  await page.evaluate(switchVisibility,false);
  assert.equal(await page.locator('#nyxAwayCover').isVisible(),false);
  assert.equal(await page.locator('input').inputValue(),'preserved');
  await page.evaluate(()=>window.dispatchEvent(new Event('blur')));
  await page.waitForTimeout(30);
  assert.equal(await page.locator('#nyxAwayCover').isVisible(),false,'Focus remaining inside Nyx must not show a cover');
  await page.evaluate(()=>{Object.defineProperty(document,'hasFocus',{configurable:true,value:()=>false});dispatchEvent(new Event('blur'));});
  await page.locator('#nyxAwayCover').waitFor({state:'visible'});
  await page.evaluate(()=>{delete document.hasFocus;dispatchEvent(new Event('focus'));});
  await page.locator('#nyxAwayCover').waitFor({state:'hidden'});
  assert.equal(await page.locator('input').inputValue(),'preserved');
  await page.locator('iframe').evaluate(frame=>{frame.removeAttribute('srcdoc');frame.src='/apps/music/'});
  await page.frameLocator('iframe').getByRole('button',{name:'Music app'}).click({button:'right'});
  assert.equal(await page.getByRole('menu',{name:'Nyx'}).count(),1);await page.keyboard.press('Escape');
  await page.frameLocator('iframe').getByRole('button',{name:'Music app'}).click();
  await page.waitForTimeout(30);
  assert.equal(await page.locator('#nyxAwayCover').isVisible(),false,'Focusing an embedded app must keep it visible');
  await page.evaluate(()=>{Object.defineProperty(document,'hasFocus',{configurable:true,value:()=>false});dispatchEvent(new Event('blur'));});
  await page.locator('#nyxAwayCover').waitFor({state:'visible'});
  await page.evaluate(()=>{delete document.hasFocus;});
  await page.locator('#nyxAwayCover').waitFor({state:'hidden'});
  await page.keyboard.press('F12');
  assert.equal(await page.locator('body').innerHTML(),'');assert.equal(await page.locator('script,iframe,link').count(),0);
  await page.evaluate(switchVisibility,true);await page.evaluate(switchVisibility,false);
  assert.equal(await page.locator('body').innerHTML(),'','Returning to the workspace tab cannot undo F12 blanking');
  await page.mouse.click(100,100);await page.keyboard.press('Escape');await page.keyboard.press('F12');
  await page.evaluate(()=>{document.body.append(document.createElement('div'));});await page.waitForTimeout(100);
  assert.equal(await page.locator('body').innerHTML(),'');
  await page.reload();assert.equal(await page.locator('input').count(),1);
  await page.frameLocator('iframe').getByRole('button').click();await page.keyboard.press('F12');
  assert.equal(await page.locator('body').innerHTML(),'');
  await page.reload();await page.keyboard.press('Control+Shift+I');assert.equal(await page.locator('body').innerHTML(),'');
  console.log('PASS Nyx menu, disabled actions, keyboard, mobile bounds, tab/window away cover, automatic return including iframe focus, blank-until-reload and iframe shortcut.');
}finally{await workspace.close();await new Promise(resolve=>server.close(resolve));}
