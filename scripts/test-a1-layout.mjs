import assert from 'node:assert/strict';
import express from 'express';
import {chromium} from 'playwright';
const server = express().use(express.static(process.env.NYX_TEST_STATIC_ROOT || '.')).use(express.static('dist')).listen(0, '127.0.0.1');
await new Promise(resolve => server.once('listening', resolve));
const browser = await chromium.launch({channel: 'msedge'});
try {
  const page = await browser.newPage({viewport: {width: 1440, height: 960}});
  const errors = [];
  let requests = 0;
  page.on('pageerror', error => errors.push(error.message));
  await page.route('**/api/**', async route => {
    const path = new URL(route.request().url()).pathname;
    if (path.endsWith('/models')) return route.fulfill({json: {models: [{id: 'openai/gpt-fixture', label: 'GPT', text: true, vision: true},{id:'openai/gpt-fixture:batch',label:'GPT Batch',text:true}]}});
    if (path.endsWith('/providers')) return route.fulfill({json: {providers: [{id: 'shared', label: 'OpenRouter'}]}});
    if (path === '/api/nyx-ai' && route.request().method() === 'POST') {
      const payload=route.request().postDataJSON();
      assert.equal(payload.reasoningEffort,{off:'low',normal:'medium',extended:'high'}[payload.responseDepth]);
      requests++;
      await new Promise(resolve => setTimeout(resolve, 1200));
      return route.fulfill({contentType: 'text/event-stream', body: 'data: {"choices":[{"delta":{"content":"<think>A short fixture explanation.</think>Here is a thoughtful response to your idea."}}]}\n\ndata: [DONE]\n\n'});
    }
    return route.fulfill({json: {}});
  });
  await page.goto((process.env.NYX_TEST_BASE_URL || `http://127.0.0.1:${server.address().port}`) + '/ai.html');
  await page.getByRole('heading', {name: 'Welcome back', exact: true}).waitFor();
  await page.evaluate(() => window.postMessage({type: 'nyx:ai-profile', profile: {displayName: 'Alex <test>'}}, location.origin));
  await page.getByRole('heading', {name: 'Welcome back, Alex <test>', exact: true}).waitFor();
  await page.waitForFunction(()=>{const y=document.querySelector('#form').getBoundingClientRect().y;return y>350&&y<600;});
  const centered = await page.locator('#form').boundingBox();
  assert(centered.y > 350 && centered.y < 600, 'Empty composer starts in the middle');
  await page.locator('#modelTrigger').click();
  assert(await page.locator('#model option[value="openai/gpt-fixture:batch"]').isDisabled(),'Batch models cannot be submitted as interactive chat');
  assert.equal(await page.locator('#modelTrigger .ai-company-logo').count(),1,'Selected provider icon replaces the status dot');
  assert.equal(await page.locator('#providerSelect').isVisible(),false);
  assert.equal(await page.locator('#customKeyButton').isVisible(),false);
  assert(await page.locator('#modelTrigger').evaluate(node=>{
    const icon=node.querySelector('.ai-model-status').getBoundingClientRect();
    const label=node.children[1].getBoundingClientRect();
    return label.left-icon.right>=9;
  }),'Model name has room beside its icon');
  await page.getByRole('searchbox', {name: 'Search models'}).fill('GPT');
  await page.keyboard.press('Enter');
  assert.equal(requests, 0, 'Model search never submits the composer');
  await page.getByRole('button', {name: 'Close model list'}).click();
  await page.screenshot({path: '.codex-artifacts/a1-desktop.png'});
  await page.getByRole('textbox', {name: 'Message N7X A1'}).fill('Help me explore an idea');
  await page.getByRole('button', {name: 'Send message', exact: true}).click();
  await page.getByRole('status', {name: 'A1 is waiting for a response'}).waitFor();
  assert([1,3,5,6,9,10].includes(Number(await page.locator('[data-thinking-variant]').getAttribute('data-thinking-variant'))));
  await page.screenshot({path: '.codex-artifacts/a1-thinking.png'});
  await page.getByText('Here is a thoughtful response to your idea.', {exact: true}).waitFor();
  const reasoning=page.locator('.ai-reasoning');
  const compact=await reasoning.boundingBox();
  assert(compact.height<=40&&compact.width<250,'Reasoning is a compact collapsed row');
  await reasoning.locator('summary').click();
  assert(await reasoning.getByText('A short fixture explanation.',{exact:true}).isVisible());
  await reasoning.locator('summary').click();
  assert.equal(await page.getByRole('status', {name: 'A1 is waiting for a response'}).count(), 0);
  assert.equal(requests, 1);
  await page.screenshot({path: '.codex-artifacts/a1-conversation.png'});
  await page.getByRole('button', {name: 'Close conversation sidebar', exact: true}).first().click();
  await page.getByRole('button', {name: 'Open conversation sidebar', exact: true}).click();
  await page.locator('#threadSearch').fill('nonexistent');
  await page.locator('#historyEmpty').waitFor();
  assert.equal((await page.locator('#historyEmpty').textContent()).normalize('NFKC'), 'No matching chats.');
  assert.equal(await page.locator('[data-thread-id]').count(), 0);
  await page.setViewportSize({width: 390, height: 740});
  await page.reload();
  await page.getByRole('button', {name: 'Open conversation sidebar', exact: true}).waitFor();
  assert(await page.getByRole('textbox', {name: 'Message N7X A1'}).isVisible());
  await page.getByRole('button', {name: 'Open conversation sidebar', exact: true}).click();
  await page.getByRole('button', {name: 'New chat', exact: true}).click();
  await page.getByRole('heading', {name: /^Welcome back/}).waitFor();
  await page.waitForTimeout(450);
  await page.screenshot({path: '.codex-artifacts/a1-mobile.png'});
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  const send = await page.getByRole('button', {name: 'Send message', exact: true}).boundingBox();
  assert(send.x >= 0 && send.x + send.width <= 390 && send.y + send.height <= 740);
  await page.emulateMedia({reducedMotion: 'reduce'});
  assert.equal(await page.getByRole('heading', {name: /^Welcome back/}).evaluate(node => getComputedStyle(node.parentElement).animationName), 'none');
  await page.locator('#input').click();
  await page.waitForTimeout(50);
  const docked = await page.locator('#form').boundingBox();
  assert(docked.y > 500, 'Clicking the composer docks it at the bottom');
  assert.deepEqual(errors, []);
  console.log('PASS A1 desktop/mobile layout, model dialog Enter isolation, real response rendering, sidebar, search, new chat and reduced motion');
} finally {
  await browser.close();
  server.closeAllConnections();
  await new Promise(resolve => server.close(resolve));
}
