import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {memoryFirestore} from './test-ai-allowance.mjs';
import {aiModelAllowed,createAiAllowance,aiAllowanceConfig} from '../lib/ai-allowance.mjs';
import {fableTrialModel as model,fableTrialStart,fableTrialEnd,fableTrialId} from '../lib/ai-fable-trial.mjs';
const price={inputPerMillion:10,outputPerMillion:50};
const actor=(uid='member')=>({uid,requestedModel:model,createdAt:fableTrialStart});
const payload=()=>({model,messages:[{role:'user',content:'hey'}],max_tokens:2200});
let time=fableTrialStart+1000;
const db=memoryFirestore(),config=aiAllowanceConfig({NYX_AI_DAILY_BUDGET_USD:'1',NYX_AI_MONTHLY_BUDGET_USD:'30'});
const create=()=>createAiAllowance({db,config,now:()=>time});let a=create();
assert(aiModelAllowed(model,actor(),price,time));
assert(!aiModelAllowed(model,{},price,time));
assert(!aiModelAllowed(model,{...actor(),blocked:true},price,time));
assert(!aiModelAllowed(model,{...actor(),modelRules:[{model,access:'deny'}]},price,time));
assert(!aiModelAllowed(model,actor(),price,fableTrialEnd));
assert(!aiModelAllowed(model,actor(),price,fableTrialStart-1));
assert(aiModelAllowed(model,{...actor(),premium:true},price,fableTrialEnd));
const key=uid=>`nyxAiAllowance/${fableTrialId}-${createHash('sha256').update(uid).digest('hex')}`;
for(let n=0;n<5;n++){
 const s=await a.begin(actor()),p=payload();assert.equal(s.tier,'newcomer');
 const r=await a.reserve(s,'shared',p,price);
 assert.equal(p.max_tokens,1000);assert.equal(p.max_tokens*price.outputPerMillion,50000);
 assert(r.reserved>50000,'Input must not subtract from the output allowance');
 await a.settle(r,{input:100,output:1000});await a.finish(s,true);
 a=create();time+=61000;
}
assert.equal(db.records.get(key('member')).messages,5);
assert.equal(db.records.get('nyxAiAllowance/global').newcomerMoney,0,'Settled Fable replies leave general spending unchanged');
assert.equal(db.records.get('nyxAiAllowance/global').newcomerRequests,0,'Fable does not consume general request budget');
assert(db.records.get(key('member')).reserved>100000,'Removed account dollar limit must not block five replies');
const sixth=await a.begin(actor());await assert.rejects(a.reserve(sixth,'shared',payload(),price),/five Fable/);await a.finish(sixth);
assert.equal((await a.usage(actor())).fableTrial.messagesRemaining,0);
assert.equal((await a.usage(actor())).fableTrial.outputLimitUsd,.05);
const long=await a.begin(actor('long')),longPayload={...payload(),messages:[{role:'user',content:'x'.repeat(4000)}]};
await a.reserve(long,'shared',longPayload,price);assert.equal(longPayload.max_tokens,1000);await a.finish(long);
time+=61000;
const repriced=await a.begin(actor('repriced')),higher={...payload(),max_tokens:65000,max_completion_tokens:65000};
await a.reserve(repriced,'shared',higher,{inputPerMillion:10,outputPerMillion:100});assert.equal(higher.max_tokens,500);assert.equal(higher.max_completion_tokens,undefined);await a.finish(repriced);
time+=61000;
const media=await a.begin(actor('media'));await assert.rejects(a.reserve(media,'shared',{...payload(),plugins:[{id:'web'}]},price),/text response/);await a.finish(media);
const global=db.records.get('nyxAiAllowance/global');global.newcomerMoney=1000000;
const over=await a.begin(actor('global'));await a.reserve(over,'shared',payload(),price);await a.finish(over);
assert.equal(db.records.get(key('global')).messages,1,'Fable has its own campaign budget');
assert.equal(db.records.get('nyxAiAllowance/global').newcomerMoney,1000000,'Fable does not charge the general budget');
global.newcomerMoney=0;global.monthMoney=0;db.records.set('nyxAiAllowance/global',global);
time+=61000;
const concurrent=await Promise.allSettled([a.begin(actor('race')),a.begin(actor('race'))]);
assert.equal(concurrent.filter(r=>r.status==='fulfilled').length,1,'Concurrent requests cannot evade the account slot');
await a.finish(concurrent.find(r=>r.status==='fulfilled').value);
const campaignDb=memoryFirestore();
const campaign=createAiAllowance({db:campaignDb,config:aiAllowanceConfig({NYX_AI_DAILY_BUDGET_USD:'10'}),now:()=>time});
const campaignKey=`nyxAiAllowance/${fableTrialId}-global`;
campaignDb.records.set(campaignKey,{reserved:2435000});
const ca=await campaign.begin(actor('ca')),cb=await campaign.begin(actor('cb'));
const results=await Promise.allSettled([campaign.reserve(ca,'shared',payload(),price),campaign.reserve(cb,'shared',payload(),price)]);
assert.equal(results.filter(r=>r.status==='fulfilled').length,1);
assert.match(results.find(r=>r.status==='rejected').reason.message,/2\.50/);
assert(campaignDb.records.get(campaignKey).reserved<=2500000);
const accepted=results.find(r=>r.status==='fulfilled').value;
const reserved=campaignDb.records.get(campaignKey).reserved;
await campaign.settle(accepted,null);assert.equal(campaignDb.records.get(campaignKey).reserved,reserved,'Unknown cost retains reservation');
await campaign.settle(accepted,{input:1,output:1,cost:.00006});assert.equal(campaignDb.records.get(campaignKey).reserved,2435060);
await campaign.settle(accepted,{input:1,output:1,cost:.00006});assert.equal(campaignDb.records.get(campaignKey).reserved,2435060,'No double refunds');
await campaign.finish(ca);await campaign.finish(cb);time+=61000;
const cancel=await campaign.begin(actor('cancel')),cancelled=await campaign.reserve(cancel,'shared',payload(),price);
await campaign.settle(cancelled,null,true);
assert.equal(campaignDb.records.get(key('cancel')).messages,0,'Unsent request refunds message');
assert.equal(campaignDb.records.get(campaignKey).reserved,2435060,'Unsent request refunds dollars');
await campaign.finish(cancel);
const pending=await a.begin(actor('expires'));time=fableTrialEnd;
await assert.rejects(a.reserve(pending,'shared',payload(),price),/Premium|not enabled/);await a.finish(pending);
await assert.rejects(a.begin(actor('expired')),/not enabled/);
const independent=createAiAllowance({db:memoryFirestore(),config:aiAllowanceConfig({NYX_AI_DAILY_BUDGET_USD:'0'}),now:()=>fableTrialStart+1000});
const independentSession=await independent.begin(actor('independent'));const independentReceipt=await independent.reserve(independentSession,'shared',payload(),price);assert(independentReceipt.reserved>50000,'Trial prices are enforced even when general budget is disabled');await independent.finish(independentSession);
