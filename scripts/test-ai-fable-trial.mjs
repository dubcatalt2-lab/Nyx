import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
import {memoryFirestore} from './test-ai-allowance.mjs';
import {aiModelAllowed,createAiAllowance,aiAllowanceConfig} from '../lib/ai-allowance.mjs';
import {fableTrialModel as model,fableTrialStart,fableTrialEnd,fableTrialId} from '../lib/ai-fable-trial.mjs';
const price={inputPerMillion:10,outputPerMillion:50};
const actor=(uid='member')=>({uid,requestedModel:model,trusted:true,createdAt:0});
const payload=()=>({model,messages:[{role:'user',content:'Hello'}],max_tokens:2200});
let time=fableTrialStart+1000;
const db=memoryFirestore(),config=aiAllowanceConfig({NYX_AI_DAILY_BUDGET_USD:'100',NYX_AI_MONTHLY_BUDGET_USD:'1000',NYX_AI_ACCOUNT_REQUESTS_PER_MINUTE:'60'});
const create=()=>createAiAllowance({db,config,now:()=>time});let a=create();
assert(aiModelAllowed(model,actor(),price,time));
assert(!aiModelAllowed(model,{},price,time));
assert(!aiModelAllowed(model,{...actor(),blocked:true},price,time));
assert(!aiModelAllowed(model,{...actor(),modelRules:[{model,access:'deny'}]},price,time));
assert(!aiModelAllowed(model,actor(),price,fableTrialEnd));
assert(!aiModelAllowed(model,actor(),price,fableTrialStart-1));
assert(aiModelAllowed(model,{...actor(),premium:true},price,fableTrialEnd));
const key=`nyxAiAllowance/${fableTrialId}-${createHash('sha256').update('member').digest('hex')}`;
for(let n=0;n<5;n++){
 const s=await a.begin(actor()),p={...payload(),max_tokens:100},r=await a.reserve(s,'shared',p,price);
 assert(r.reserved<=50000);assert(p.max_tokens<2200);
 await a.settle(r,{input:5,output:5,cost:.0003});await a.finish(s,true);
 a=create();time+=61000;
}
assert.equal(db.records.get(key).messages,5);
assert(db.records.get(key).reserved<=100000);
const third=await a.begin(actor());await assert.rejects(a.reserve(third,'shared',payload(),price),/five Fable/);await a.finish(third);
assert.equal((await a.usage(actor())).fableTrial.messagesRemaining,0);
const tooLong=await a.begin(actor('long'));await assert.rejects(a.reserve(tooLong,'shared',{...payload(),messages:[{role:'user',content:'x'.repeat(10000)}]},price),/budget/);await a.finish(tooLong);
const media=await a.begin(actor('media'));await assert.rejects(a.reserve(media,'shared',{...payload(),plugins:[{id:'web'}]},price),/text response/);await a.finish(media);
const globalKey=`nyxAiAllowance/${fableTrialId}-global`;
db.records.set(globalKey,{reserved:4999999});
const over=await a.begin(actor('global'));await assert.rejects(a.reserve(over,'shared',payload(),price),/budget|spending/);await a.finish(over);
db.records.set(globalKey,{reserved:4950000});
const s1=await a.begin(actor('race1')),s2=await a.begin(actor('race2'));
const race=await Promise.allSettled([a.reserve(s1,'shared',payload(),price),a.reserve(s2,'shared',payload(),price)]);
assert.equal(race.filter(r=>r.status==='fulfilled').length,1);
assert(db.records.get(globalKey).reserved<=5000000);
await a.finish(s1);await a.finish(s2);
const pending=await a.begin(actor('expires'));time=fableTrialEnd;
await assert.rejects(a.reserve(pending,'shared',payload(),price),/Premium|not enabled/);await a.finish(pending);
await assert.rejects(a.begin(actor('expired')),/not enabled/);
console.log('PASS Fable trial: access, expiry, deny rules, five messages across restart, output cap, oversized input, tools, global cap and concurrent reservations');
