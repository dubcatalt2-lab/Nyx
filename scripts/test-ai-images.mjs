import assert from 'node:assert/strict';
import sharp from 'sharp';
import vm from 'node:vm';
import {readFile} from 'node:fs/promises';
import {parse} from 'acorn';
import {aiImageContent} from '../lib/ai-image.mjs';
import {aiAllowanceConfig,createAiAllowance} from '../lib/ai-allowance.mjs';
import {memoryFirestore} from './test-ai-allowance.mjs';

const source=await readFile(new URL('../server.js',import.meta.url),'utf8');
const node=parse(source,{ecmaVersion:'latest',sourceType:'module'}).body.find(n=>n.type==='FunctionDeclaration'&&n.id.name==='nyxAiNormalizeCatalog');
const ctx=vm.createContext({});vm.runInContext(source.slice(node.start,node.end),ctx);
const models=ctx.nyxAiNormalizeCatalog([{id:'google/gemini-2.5-flash-lite',architecture:{input_modalities:['text','image']}},{id:'deepseek/deepseek-v4-flash',architecture:{input_modalities:['text']}}]);
assert.equal(models[0].vision,true);assert.equal(models[1].vision,false);
const buffer=await sharp({create:{width:2000,height:1000,channels:3,background:'#ed3020'}}).png().toBuffer();
const content=await aiImageContent({buffer},'What color is this?',models[0]);
assert.equal(content[0].text,'What color is this?');assert.equal(content[1].type,'image_url');
const pixels=Buffer.from(content[1].image_url.url.split(',')[1],'base64');
const metadata=await sharp(pixels).metadata();assert.equal(metadata.width,1600);assert.equal(metadata.height,800);
const {data}=await sharp(pixels).raw().toBuffer({resolveWithObject:true});assert.ok(data[0]>220&&data[1]<60&&data[2]<50,'The actual red image reaches the payload');
await assert.rejects(aiImageContent({buffer},'read',models[1]),e=>e.status===400&&/Choose Gemini 2.5 Flash Lite/.test(e.message));
await assert.rejects(aiImageContent({buffer:Buffer.from('invalid')},'read',models[0]),/decode/);
const lunaContent=await aiImageContent({buffer},'Read the image',{id:'openai/gpt-5.6-luna',vision:true});
assert.equal(lunaContent[1].type,'image_url');
assert.equal(aiAllowanceConfig({NYX_AI_MODEL_PRICES_JSON:JSON.stringify({'shared:openai/gpt-5.6-luna':{inputPerMillion:.25,outputPerMillion:1.2}})}).prices['shared:openai/gpt-5.6-luna'].imageTokens,8192);
const config=aiAllowanceConfig({NYX_AI_DAILY_BUDGET_USD:'1',NYX_AI_MODEL_PRICES_JSON:JSON.stringify({'shared:google/gemini-2.5-flash-lite':{inputPerMillion:.1,outputPerMillion:.4,maxInputTokens:32768}})});
assert.equal(config.prices['shared:google/gemini-2.5-flash-lite'].imageTokens,8192);
const allowance=createAiAllowance({db:memoryFirestore(),config});
const session=await allowance.begin({uid:'image-test',premium:true,createdAt:Date.parse('2026-01-01')});
const reservation=await allowance.reserve(session,'shared',{model:models[0].id,messages:[{role:'user',content}],max_tokens:700});
assert.ok(reservation.tokens>=8192+700,'Image tokens are reserved before inference');
assert.ok(reservation.reserved>0);await allowance.settle(reservation,null,true);await allowance.finish(session);
const main=source.slice(source.indexOf('  const suppliedImage = req.body?.image;'),source.indexOf('  const wantsStream = req.body?.stream'));
assert.match(main,/await aiImageContent\(image,prompt,modelInfo\)/);assert.doesNotMatch(main,/nyxAiAnalyzeImage/);
console.log('PASS: OpenRouter vision metadata, actual image pixels, bounded resizing, text-only rejection, malformed uploads and image budget reservation');

const parameterNode=parse(source,{ecmaVersion:'latest',sourceType:'module'}).body.find(n=>n.type==='FunctionDeclaration'&&n.id.name==='nyxAiApplySupportedParameters');
vm.runInContext(source.slice(parameterNode.start,parameterNode.end),ctx);
const parameterModels=ctx.nyxAiNormalizeCatalog([{id:'openai/gpt-5.6-luna',supported_parameters:['max_tokens','reasoning']},{id:'google/gemini-2.5-flash-lite',supported_parameters:['max_tokens','temperature']}]);
assert.equal(ctx.nyxAiApplySupportedParameters({temperature:0,max_tokens:300},parameterModels[0]).temperature,undefined);
assert.equal(ctx.nyxAiApplySupportedParameters({temperature:0,max_tokens:300},parameterModels[1]).temperature,0);
assert.match(source,/nyxAiApplySupportedParameters\(providerPayload,modelInfo\)/);
console.log('PASS: provider-declared parameters omit unsupported Luna temperature while preserving Gemini settings');
