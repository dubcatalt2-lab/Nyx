import assert from 'node:assert/strict';
import {createAnimeSources,pickAnimeMapping,parseAnimePage} from '../lib/movie-anime-sources.mjs';
import {movieSourceUrl} from '../apps/movies/providers.mjs';
const rows=[{themoviedb_id:{tv:12},season:{tmdb:1},anilist_id:30},{themoviedb_id:{tv:12},season:{tmdb:1},anilist_id:40,episode_offset:{tmdb:12}}];
assert.deepEqual(pickAnimeMapping(rows,12,1,12),{anilistId:30,episode:12});
assert.deepEqual(pickAnimeMapping(rows,12,1,13),{anilistId:40,episode:1});
assert.equal(pickAnimeMapping(rows,12,2,1),null);
assert.equal(pickAnimeMapping([...rows,{...rows[0],anilist_id:50}],12,1,1),null);
const page=(id=40,tmdb=12,slug='test-anime-abc')=>`data:{anime:{id:"${id}",anilistId:${id},tmdbId:"${tmdb}",slug:"${slug}",totalEpisodes:12},epNum:"1"}`;
assert.equal(parseAnimePage(page(40,13),40,12),null);
assert.equal(parseAnimePage(page(30),40,12),null);
assert.equal(parseAnimePage(page(40,12,'../../evil'),40,12),null);
let calls=0;const resolve=createAnimeSources({fetchImpl:async url=>{calls++;return new Response(url.includes('githubusercontent')?JSON.stringify(rows):page());}});
const [one,two]=await Promise.all([resolve(12,1,13),resolve(12,1,14)]);
assert.match(one[0].url,/\/test-anime-abc\/1\?/);assert.match(two[0].url,/\/test-anime-abc\/2\?/);assert.equal(calls,2);
assert.deepEqual(one.map(s=>s.id),['animex','aniembed']);
assert.equal(one[1].url,'https://aniembed.se/e/40/1?lang=sub&autoplay=1&t=0');
assert.equal(two[1].url,'https://aniembed.se/e/40/2?lang=sub&autoplay=1&t=0');
assert.equal(movieSourceUrl(one[1].url),one[1].url);
for(const url of [one[1].url+'&t=1',one[1].url+'&url=https://evil.test',one[1].url.replace('aniembed.se','aniembed.se.evil.test'),one[1].url.replace('/40/1','/40/0'),one[1].url.replace('https:','http:'),one[1].url+'#extra'])assert.equal(movieSourceUrl(url),null);
assert.match((await resolve(12,1,24))[0].url,/hasNext=0$/);
assert.deepEqual((await resolve(12,1,25)).map(s=>s.id),['aniembed'],'AnimeX episode availability must not suppress AniEmbed');assert.equal(calls,2);
assert.deepEqual(await resolve(99,1,1),[]);
const unavailable=createAnimeSources({fetchImpl:async()=>new Response('',{status:403})});assert.deepEqual(await unavailable(12,1,1),[]);
const independent=createAnimeSources({fetchImpl:async url=>url.includes('githubusercontent')?new Response(JSON.stringify(rows)):new Response('',{status:503})});
assert.deepEqual(await independent(12,1,13),[one[1]],'AniEmbed remains available when AnimeX lookup fails');
assert.deepEqual(await independent(12,2,1),[],'No guessed season identities');
console.log('PASS AnimeX identity, season/offset boundaries, ambiguity, URL validation, episode limits, caching, request deduplication and upstream failure');
