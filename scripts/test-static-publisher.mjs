import assert from 'node:assert/strict';
import { createHash } from 'node:crypto';
import { prepareStaticPackage, staticLauncher, validateStaticManifest } from '../apps/jsdelivr-publisher/static-publish.js';
import { staticPublisherFixture } from './static-publisher-fixture.mjs';
import { StaticPackagePreparation } from '../lib/static-package-preparation.mjs';

const { manifest, contents } = await staticPublisherFixture();
const calls = [];
let existing = null;
let previousMarker;
let corruptRead = false;
const expectedMarker = JSON.stringify({ format: manifest.format, schema: 1, revision: manifest.revision, base: '/gh/test/repo@main/nyx-static/' });
const gitSha = value => createHash('sha1').update(`blob ${Buffer.byteLength(value)}\0`).update(value).digest('hex');
async function api(path, options = {}) {
  calls.push({ path, ...options });
  if (path.endsWith('/trees/head')) return { tree: existing ? [{ path: 'nyx-static', type: 'tree', sha: 'existing' }] : [] };
  if (path.endsWith('/trees/existing')) return { tree: previousMarker ? [{ path: 'nyx-package.json', type: 'blob', sha: gitSha(previousMarker) }] : [] };
  if (path.includes('/blobs/') && !options.method) return { content: Buffer.from(previousMarker).toString('base64') };
  if (path.endsWith('/blobs') && options.method === 'POST') return { sha: 'binary-sha' };
  if (path.endsWith('/trees') && options.method === 'POST') return { sha: 'package-tree' };
  throw Error('Unexpected API: ' + path);
}
const prepare = () => prepareStaticPackage({ api, repository: 'test/repo', branch: 'main', headTree: 'head', manifest, readBytes: path => corruptRead ? Buffer.from('bad') : Buffer.from(contents[path]) });
assert.doesNotMatch(staticLauncher(), /iframe|https:\/\/nyxlearning\.org/);
assert.match(staticLauncher(), /nyx-static\/Nyx\.svg/);
const entry = await prepare();
assert.equal(entry.type, 'tree');
assert.equal(entry.path, 'nyx-static');
const tree = JSON.parse(calls.find(call => call.method === 'POST' && call.path.endsWith('/trees')).body);
assert.equal(tree.base_tree, undefined, 'replace package subtree without retaining stale assets');
assert.equal(tree.tree.length, 5);
assert.equal(tree.tree.find(file => file.path === 'library-worker.js').content, 'const base="/gh/test/repo@main/nyx-static/";');
assert.equal(tree.tree.find(file => file.path === 'pixel.bin').sha, 'binary-sha');
assert.equal(tree.tree.find(file => file.path === 'nyx-package.json').content, expectedMarker);
assert.equal(calls.some(call => call.path.includes('/refs/') || call.path.includes('/commits')), false, 'preparation must never publish a partial branch');
existing = true; previousMarker = expectedMarker; calls.length = 0;
assert.equal((await prepare()).sha, 'existing');
assert.equal(calls.some(call => call.method === 'POST'), false, 'identical package must be reused');
previousMarker = JSON.stringify({ format: manifest.format, schema: 1, revision: 'old' }); calls.length = 0;
assert.equal((await prepare()).sha, 'package-tree');
previousMarker = JSON.stringify({ format: 'another-project' });
await assert.rejects(prepare, /another project/);
previousMarker = null;
await assert.rejects(prepare, /not a Nyx package/);
existing = null; corruptRead = true;
await assert.rejects(prepare, /failed verification/);
assert.throws(() => validateStaticManifest({ ...manifest, files: [{ ...manifest.files[0], path: '../server.js' }] }), /unsupported/);
let finish, preparations = 0;
const pending = new Promise(resolve => { finish = resolve; });
const preparation = new StaticPackagePreparation({ waitMs: 5 });
const start = () => { preparations++; return pending; };
for (let i = 0; i < 3; i++) await assert.rejects(preparation.get('package', start), error => error.code === 'STATIC_PACKAGE_PREPARING' && error.status === 429);
assert.equal(preparations, 1, 'polling and simultaneous users reuse the in-flight asset upload');
finish(entry);
assert.deepEqual(await preparation.get('package', start), entry);
await assert.rejects(preparation.get('failed', () => { throw Error('Upload failed'); }), /Upload failed/);
assert.deepEqual(await preparation.get('failed', () => entry), entry, 'failed preparation can retry without advancing a branch');
console.log('Static package publish tests passed: reuse, bounded assets, binary integrity, base paths, protected foreign folder, atomic branch boundary and no site iframe.');
